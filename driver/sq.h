#define PFLAG (MAXD-1)                          /* pt_t slot holding "children may skip |.| sums" (DIM < MAXD) */

/* ---- sum.c: hierarchical Sinc sum ---- */
typedef struct { double S[3], Ah, ref, prune, trunc, unres, t; long nev, nq, kept_top; } res_t;
extern int GROW;
res_t hsum(const graph_t *g, double h, int N, double eps, int top);

/* ---- checkpoint.c ---- */
typedef struct { signed char k[MAXD]; } pt_t;   /* |k_i| <= K <= KMAX; slot PFLAG holds flags when DIM < MAXD */
#define KMAX 127
static inline void ptget(const pt_t *p, int *k){ for(int i = 0; i < MAXD; i++) k[i] = p->k[i]; }
typedef struct { pt_t *p; long n, cap; } vec_t;
void push(vec_t *v, const int *k);
void uniq(vec_t *v);
typedef struct {                             /* state of hsum between refine blocks */
    int lev; long next;                      /* level being refined, first unprocessed cell */
    double s, a, drop, u; long ne, q;        /* partial sums of that level */
    double Slev[16]; int nl;
    res_t R;
    vec_t cur, nxt;
    /* run state outside the point lists (format SQCK4; older formats are not read) */
    double es[5]; long cnt[3]; int esok;     /* shadow sums ES1 ES2, predictor check PDS PDA PDN; PSKIP ABSKIPPED ABMISS; shadow on */
    void *vs; long vcap, vn; int vsz;        /* the predictor's table of 2h values: vcap slots of vsz bytes */
} ckpt_t;
extern double CKPT_EVERY;                    /* seconds between checkpoints (0 = off) */
void ckpt_name(char *buf, size_t n, const graph_t *g);
int  ckpt_save(const graph_t *g, double h, int N, double eps, int top, const ckpt_t *c);
int  ckpt_load(const graph_t *g, double h, int N, double eps, int top, ckpt_t *c);
void ckpt_remove(const graph_t *g);
