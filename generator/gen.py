"""
Generate C sources for all L-loop vertex graphs without lepton loops.

    python3 gen.py L OUTDIR [--jobs N] [--only VOLKOVNAME ...]

Dirac algebra and kernel optimisation use FORM (https://github.com/form-dev/form) when the
`form` executable is on the PATH (or $FORM): exact tables in seconds and node polynomials written as
FORM Format O3 code, which makes the four-loop kernels 1.5-2x faster.  Without FORM (or with
GEN_FORM=0) the original Python path (numpy tables, factored trees) is used, with a warning for L=4.

Writes OUTDIR/g<L>_<i>.c (one file per graph up to mirror symmetry, precision-templated) and
OUTDIR/table_<L>.h (the graph registry used by the driver).  Dirac tables are cached in
cache_dirac.pkl next to this script.
"""
import sys, os, pickle, time, argparse, multiprocessing as mp
import graphs as gr, build, dirac, formdirac

def use_form(L):
    """FORM by default; the Python path when FORM is missing or GEN_FORM=0 (warns at four loops)."""
    if os.environ.get('GEN_FORM', '1') == '0':
        on = False; why = 'GEN_FORM=0'
    else:
        on = formdirac.available() is not None; why = 'FORM executable "%s" not found' % formdirac.FORM
    if not on and L >= 4:
        sys.stderr.write('*** WARNING: %s -- generating the four-loop kernels with the Python Dirac algebra.\n'
                         '*** The tables take hours and the kernels run 1.5-2x slower than FORM-optimised ones;\n'
                         '*** the shipped kernels/g4 were made with FORM (https://github.com/form-dev/form/releases).\n' % why)
    dirac.USE_FORM = build.USE_FORM = on
    return on

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, 'cache_dirac.pkl')

def _tab(args):
    key, chain, nslots, kind = args
    t = time.time(); tb = dirac.table(chain, nslots, kind)
    return key, tb, time.time() - t

class DirCache:
    """Dirac-table cache kept as one pickle per table in a directory: bounded memory, shared by
    all batches and workers, resumable (a table is written atomically when it is finished)."""
    def __init__(self, d):
        self.d = d; os.makedirs(d, exist_ok=True); self.mem = {}
    def _p(self, k): return os.path.join(self.d, k + '.pkl')
    def __contains__(self, k): return k in self.mem or os.path.exists(self._p(k))
    def __getitem__(self, k):
        if k not in self.mem: self.mem[k] = pickle.load(open(self._p(k), 'rb'))
        return self.mem[k]
    def __setitem__(self, k, v):
        pickle.dump(v, open(self._p(k) + '.tmp', 'wb')); os.replace(self._p(k) + '.tmp', self._p(k))
    def drop(self): self.mem = {}

_CACHE = None; _OUT = None
def _emit(args):
    i, g, w = args
    cname = 'g%d_%02d' % (g.L, i)
    t = time.time()
    pt, info = build.gen_graph(g, cname, _CACHE)
    wr, D, ngl, glc = build.gen_wrapper(g, cname)
    # the FORM tag is what the Makefile looks for; Python-path headers are unchanged (byte-identical regen)
    src = ["/* Generated by gen.py: %d-loop graph '%s' (Volkov notation), mirror weight %d.%s\n"
           " * terms %d, nodes %d, Dirac structures %d, dimension %d, GL points %d */" %
           (g.L, g.volkov(), w, '  Dirac algebra: FORM %s.' % build.FORM_LEVEL if build.USE_FORM else '',
            info['nterms'], info['nnodes'], info['nstruct'], D, ngl),
           '#include "common.h"', glc,
           '#define REAL double', '#define FN(x) x##_d', pt, wr, '#undef REAL', '#undef FN',
           '#define REAL QREAL', '#define FN(x) x##_q', pt, wr, '#undef REAL', '#undef FN',
           'const graph_t G_%s={"%s","%s",%d,%d,%d,%d,%d,f_%s_d,f_%s_q,pt_%s_d,pt_%s_q};' %
           (cname, cname, g.volkov(), g.L, D, w, g.n, 2*g.L, cname, cname, cname, cname)]
    open(os.path.join(_OUT, cname + '.c'), 'w').write("\n".join(src) + "\n")
    return cname, '%s  %-22s w=%d  D=%d terms=%2d nodes=%2d structs=%5d maxw=%d  %.1fs' % (
        cname, g.volkov(), w, D, info['nterms'], info['nnodes'], info['nstruct'], info['maxw'], time.time()-t)

def write_table(out, L, entries):
    tb = ['/* Generated by gen.py */', '#include "common.h"']
    tb += ['extern const graph_t G_%s;' % c for c in entries]
    tb.append('static const graph_t *GRAPHS_%d[]={%s};' % (L, ",".join('&G_%s' % c for c in entries)))
    tb.append('#define NGRAPHS_%d %d' % (L, len(entries)))
    open(os.path.join(out, 'table_%d.h' % L), 'w').write("\n".join(tb) + "\n")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('L', type=int); ap.add_argument('out')
    ap.add_argument('--jobs', type=int, default=os.cpu_count())
    ap.add_argument('--only', nargs='*')
    ap.add_argument('--range', help='A:B -- only graphs A..B-1 of the full list (names stay global)')
    ap.add_argument('--cache', default=CACHE, help='Dirac-table cache file')
    ap.add_argument('--table-only', action='store_true', help='only write table_<L>.h for all graphs')
    ap.add_argument('--cache-dir', help='keep Dirac tables as one file each in this directory (instead of --cache)')
    ap.add_argument('--missing', action='store_true', help='skip graphs whose OUTDIR/g<L>_<i>.c already exists')
    ap.add_argument('--dirac-only', action='store_true', help='only compute the Dirac tables, emit no C')
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not a.table_only: use_form(a.L)
    build.NW = max(build.NW, a.L)   # Wick counts reach L-1 (4 at five loops); 4 keeps L <= 4 byte-identical
    allreps = gr.enumerate_graphs(a.L)
    names = ['g%d_%02d' % (a.L, i) for i in range(len(allreps))]
    if a.table_only:
        write_table(a.out, a.L, names); return
    if a.cache_dir: cache = DirCache(a.cache_dir)
    else: cache = pickle.load(open(a.cache, 'rb')) if os.path.exists(a.cache) else {}
    reps = list(enumerate(allreps))
    if a.range:
        lo, hi = (int(x) for x in a.range.split(':')); reps = reps[lo:hi]
    if a.only: reps = [(i, gw) for i, gw in reps if gw[0].volkov() in a.only]
    if a.missing:
        fn = lambda i: os.path.join(a.out, 'g%d_%02d.c' % (a.L, i))
        reps = [(i, gw) for i, gw in reps if not (os.path.exists(fn(i)) and os.path.getsize(fn(i)) > 0)]
    idx = [i for i, _ in reps]; reps = [gw for _, gw in reps]
    # 1. collect all node tables needed, compute missing ones in parallel
    import hashlib
    need = {}
    for g, w in reps:
        for sign, ops in gr.terms(g):
            F = tuple(ops.keys())
            for seg, op in ops.items():
                kids = gr.children(seg, F)
                kind = 'F2' if op == 'A' else ('SE' if g.segment(*seg)['kind'] == 'SE' else 'V0')
                nd = build.Node(g, seg, kids, kind)
                key = repr((nd.chain, len(nd.slots), nd.kind))
                h = hashlib.md5(key.encode()).hexdigest()
                if h not in cache: need[h] = (h, nd.chain, len(nd.slots), nd.kind)
    print('graphs %d, new Dirac tables %d' % (len(reps), len(need)), flush=True)
    if need:
        jobs = sorted(need.values(), key=lambda j: -len(j[1]))
        last = time.time()
        with mp.get_context('fork').Pool(a.jobs) as pool:     # fork: workers inherit dirac.USE_FORM (macOS defaults to spawn)
            for k, tb, dt in pool.imap_unordered(_tab, jobs):
                cache[k] = tb; print('  table %s: %d structures, %.0fs' % (k[:8], len(tb), dt), flush=True)
                if a.cache_dir: cache.drop(); continue
                if time.time() - last > 300:        # checkpoint the cache every 5 minutes
                    pickle.dump(cache, open(a.cache + '.tmp', 'wb')); os.replace(a.cache + '.tmp', a.cache); last = time.time()
        if not a.cache_dir: pickle.dump(cache, open(a.cache + '.tmp', 'wb')); os.replace(a.cache + '.tmp', a.cache)
    if a.dirac_only: return
    # 2. emit C, one graph per worker (the cache is inherited by the forked workers)
    global _CACHE, _OUT
    _CACHE, _OUT = cache, a.out
    work = [(i, g, w) for i, (g, w) in zip(idx, reps)]
    if a.jobs > 1 and len(work) > 1:
        with mp.get_context('fork').Pool(a.jobs) as pool:
            res = pool.map(_emit, work, chunksize=1)
    else:
        res = [_emit(x) for x in work]
    entries = []
    for cname, line in res:
        entries.append(cname); print(line, flush=True)
    if a.range or a.only:
        print('(table_%d.h not written for a partial run; use --table-only)' % a.L)
    else:
        write_table(a.out, a.L, entries)

if __name__ == '__main__':
    main()
