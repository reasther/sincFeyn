"""
Four-loop light-by-light graphs with a one-loop vacuum polarization Pi2 on one of the three
photons joining the open line to the light-by-light loop (18 diagrams: 6 orderings x 3 photons;
Laporta set 22, Kinoshita group IV(a)).  The three-loop point function of lbl.py (six orderings
and their zero-momentum subtractions) is evaluated with the photon parameter shifted by the Pi2
parameter c = ab/(a+b), minus unshifted, exactly as vp.py does for the vertex graphs.

    python3 lblvp.py OUTDIR    -> l4_vp.c, lbltable_4.h
"""
import os, sys, pickle
from fractions import Fraction
import build, lbl, vp

def main(out):
    import lblcommon; lblcommon.use_form()
    cf = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cache_lbl.pkl')
    cache = pickle.load(open(cf, 'rb'))
    cname = 'l4_vp'; base = cname + '_b'
    pt = lbl.pt_code(cache, base)
    p = ["static REAL FN(p_%s)(const REAL *x, const REAL *v, REAL *ab){" % cname,
         "  const REAL a=v[0], b=v[1], S=a+b, c=a*b/S, om=(REAL)(%d)*a*b/(S*S*S*S);" % vp.OMEGA,
         "  REAL y[9], t, ta, tot, tota;",
         "  tot=-3*FN(pt_%s)(x,S,&ta); tota=3*ta;" % base]
    for j in (6, 7, 8):
        p.append("  for(int i=0;i<9;i++) y[i]=x[i]; y[%d]+=c; t=FN(pt_%s)(y,S,&ta); tot+=t; tota+=ta;" % (j, base))
    p.append("  *ab=RABS(om)*tota; return om*tot;\n}")
    p = "\n".join(p)
    xs, ws = build.gauss_legendre01(4)
    glc = "static const double GLX_%s[4]={%s}, GLW_%s[4]={%s};" % (cname, ",".join(repr(float(x)) for x in xs), cname, ",".join(repr(float(w)) for w in ws))
    norm = -Fraction(-1, 4)**3/16          # as g3_lbl; omega carries the Pi2 loop
    # Cheng-Wu: photon a2 (parameter 7) = 1, the one the open-line mirror (a1 <-> a3) keeps in place,
    # so the driver can fold over the mirror too (the Pi2 sits on each photon in turn, so the sum is
    # mirror symmetric).  GEN_LBLCW0=1: a1 = 1 (parameter 6), the kernel before 2026-10-26.
    cw0 = os.environ.get('GEN_LBLCW0', '0') == '1'
    wr = ["static REAL FN(f_%s)(const REAL *sf, REAL *ab){" % cname,
          ("  REAL s[9]; const REAL sig=sf[0]; s[0]=sf[1]; s[1]=sf[2]; s[3]=sf[3]; s[4]=sf[4]; s[6]=1; s[7]=sf[5]; s[8]=sf[6];" if cw0 else
           "  REAL s[9]; const REAL sig=sf[0]; s[0]=sf[1]; s[1]=sf[2]; s[3]=sf[3]; s[4]=sf[4]; s[6]=sf[5]; s[7]=1; s[8]=sf[6];"),
          "  const REAL *v=sf+7; REAL acc=0, aa=0, a;",
          "  for(int g=0;g<4;g++){ const REAL u=(REAL)GLX_%s[g]; s[2]=sig*u; s[5]=sig*(1-u);" % cname,
          "    const REAL wg=(REAL)GLW_%s[g]; acc+=wg*FN(p_%s)(s,v,&a); aa+=wg*a; }" % (cname, cname),
          "  const REAL nrm=%s*sig;" % build.cnum(norm),
          "  *ab=RABS(nrm)*aa; return nrm*acc;\n}"]
    wr = "\n".join(wr)
    title = 'LbL + Pi2 on a photon (18 diagrams)'
    src = ["/* Generated by lblvp.py: %s */" % title, '#include "common.h"', glc,
           '#define REAL double', '#define FN(x) x##_d', pt, p, wr, '#undef REAL', '#undef FN',
           '#define REAL QREAL', '#define FN(x) x##_q', pt, p, wr, '#undef REAL', '#undef FN',
           'const graph_t G_%s={"%s","%s",4,9,1,9,%d,f_%s_d,f_%s_q,0,0};' % (cname, cname, title, 6 if cw0 else 7, cname, cname)]
    open(os.path.join(out, cname + '.c'), 'w').write("\n".join(src) + "\n")
    write_table(out)
    print(cname)

def write_table(out):
    """lbltable_4.h listing every l4_*.c in OUTDIR (lblvp.py, lbl4c.py, lbl4d.py all call this)."""
    import glob
    names = sorted(os.path.basename(f)[:-2] for f in glob.glob(os.path.join(out, 'l4_*.c'))
                   if 'const graph_t G_' in open(f).read())          # skips lbl4b.py's part files
    tb = ['/* Generated by lblvp.write_table */', '#include "common.h"'] + ['extern const graph_t G_%s;' % c for c in names]
    tb += ['static const graph_t *LBLGRAPHS_4[]={%s};' % ",".join('&G_%s' % c for c in names), '#define NLBLGRAPHS_4 %d' % len(names)]
    open(os.path.join(out, 'lbltable_4.h'), 'w').write("\n".join(tb) + "\n")

if __name__ == '__main__':
    main(sys.argv[1])
