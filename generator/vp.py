"""
Vertex graphs with one-loop vacuum-polarization (electron loop) insertions on photon lines.

A one-loop VP loop with Schwinger parameters (a, b) inserted in photon j turns the photon
propagator into  D(k) [Pi(k^2) - Pi(0)],  Pi(k^2) = int da db omega(a,b) e^{-(a+b)} e^{c k^2},
c = ab/(a+b), with Pi taken from the gauge-invariant k^mu k^nu coefficient of the loop.  In
Schwinger form this shifts the photon parameter s_j -> s_j + c, so the inserted graph is the base
graph (with all of its own Volkov subtraction terms) evaluated at shifted minus unshifted s_j,
times omega, with the VP loop's exponent (a+b) added to every term (argument Vx of the base
point function).  The VP loop parameters scale with the rest, so the overall scale is still
integrated analytically and n - 2L is unchanged.  omega = OMEGA * ab/(a+b)^4 (1/U^2 of the loop
included); OMEGA is fixed by the two-loop VP graph against 119/36 - pi^2/3.

    python3 vp.py OUTDIR [4]
writes v2_*.c (two-loop check), v3_*.c (three-loop: 12 graphs with a VP in a two-loop vertex graph
up to mirror symmetry -> 8 files, and the one-loop vertex with two VP loops).
"""
import os, sys, pickle, math
from fractions import Fraction
import graphs as gr, build

OMEGA = -2          # sign/normalization of the VP weight (checked against 119/36 - pi^2/3)

def mirror_photon(g, j):
    m = lambda p: 2*g.L - p
    a, b = g.arcs[j]; ma = tuple(sorted((m(a), m(b))))
    return g.mirror().arcs.index(ma)

def emit(g, w0, cname, photons, cache, out, title):
    """photons: list of photon indices of g carrying one VP loop each (may repeat)."""
    base = cname + '_b'
    pt, info = build.gen_graph(g, base, cache)
    nv = len(photons)
    # point function with VP loops: v = (a1,b1,a2,b2,...)
    o = ["static REAL FN(vp_%s)(const REAL *x, const REAL *v, REAL *ab){" % cname]
    o.append("  REAL y[%d]; for(int i=0;i<%d;i++) y[i]=x[i];" % (g.n, g.n))
    o.append("  REAL om=1, Vx=0, c[%d];" % nv)
    for t in range(nv):
        o.append("  { const REAL a=v[%d], b=v[%d], S=a+b; c[%d]=a*b/S; om*=(REAL)(%d)*a*b/(S*S*S*S); Vx+=S; }" % (2*t, 2*t+1, t, OMEGA))
    o.append("  REAL tot=0, tota=0, t, ta;")
    for mask in range(2**nv):
        sgn = (-1)**(nv - bin(mask).count('1'))
        o.append("  for(int i=0;i<%d;i++) y[i]=x[i];" % g.n)
        for t in range(nv):
            if (mask >> t) & 1: o.append("  y[%d]+=c[%d];" % (2*g.L + photons[t], t))
        o.append("  t=FN(pt_%s)(y,Vx,&ta); tot%s=t; tota+=ta;" % (base, '+' if sgn > 0 else '-'))
    o.append("  *ab=RABS(om)*tota; return om*tot;\n}")
    vpc = "\n".join(o)
    wr, D, ngl, glc = build.gen_wrapper(g, cname, inner='vp_%s' % cname, nextra=2*nv)
    src = ["/* Generated by vp.py: %s  (base graph %s, weight %d, D=%d) */" % (title, g.volkov(), w0, D),
           '#include "common.h"', glc,
           '#define REAL double', '#define FN(x) x##_d', pt, vpc, wr, '#undef REAL', '#undef FN',
           '#define REAL QREAL', '#define FN(x) x##_q', pt, vpc, wr, '#undef REAL', '#undef FN',
           # pt of a VP graph for the scale test: not provided (NULL)
           'const graph_t G_%s={"%s","%s",%d,%d,%d,%d,%d,f_%s_d,f_%s_q,0,0};' %
           (cname, cname, title, g.L + nv, D, w0, g.n, 2*g.L, cname, cname)]
    open(os.path.join(out, cname + '.c'), 'w').write("\n".join(src) + "\n")
    return cname

def photon_sets(g, w, k):
    """Multisets of k photons of g carrying one Pi2 each, one per mirror class, with weights."""
    import itertools
    out = []; seen = set()
    for ms in itertools.combinations_with_replacement(range(g.L), k):
        if ms in seen: continue
        seen.add(ms); wt = w
        if w == 1:
            mm = tuple(sorted(mirror_photon(g, j) for j in ms))
            if mm != ms: wt = 2; seen.add(mm)
        out.append((ms, wt))
    return out

def write_table(out, L, nm):
    tb = ['/* Generated by vp.py */', '#include "common.h"']
    tb += ['extern const graph_t G_%s;' % c for c in nm]
    tb.append('static const graph_t *VPGRAPHS_%d[]={%s};' % (L, ",".join('&G_%s' % c for c in nm)))
    tb.append('#define NVPGRAPHS_%d %d' % (L, len(nm)))
    open(os.path.join(out, 'vptable_%d.h' % L), 'w').write("\n".join(tb) + "\n")

def main4(out, cache):
    """Four loops, Pi2 insertions only: Pi2^3 in the one-loop vertex, Pi2^2 in the two-loop
    vertices, Pi2 in the three-loop vertices (no lepton loops in the base).  Pi4/Pi6 insertions
    and light-by-light types are not generated here."""
    names = []; i = 0
    for base in (1, 2, 3):
        for g, w in gr.enumerate_graphs(base):
            for ms, wt in photon_sets(g, w, 4 - base):
                title = 'VP: %s +%s' % (g.volkov(), '+'.join('Pi2(%d-%d)' % tuple(p+1 for p in g.arcs[j]) for j in ms))
                names.append(emit(g, wt, 'v4_%02d' % i, list(ms), cache, out, title)); i += 1
                print(names[-1], wt, title, flush=True)
    write_table(out, 4, names)

def main(out, L=3):
    import gen; gen.use_form(L)     # FORM-optimised node polynomials, as gen.py (GEN_FORM=0: Python)
    cf = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cache_dirac.pkl')
    cache = pickle.load(open(cf, 'rb'))
    if L == 4: return main4(out, cache)
    names2 = []; names3 = []
    (g1, w1), = gr.enumerate_graphs(1)
    names2.append(emit(g1, 1, 'v2_00', [0], cache, out, 'VP: 1-loop vertex + Pi2'))
    names3.append(emit(g1, 1, 'v3_00', [0, 0], cache, out, 'VP: 1-loop vertex + Pi2 Pi2'))
    i = 1
    for g, w in gr.enumerate_graphs(2):
        for ms, wt in photon_sets(g, w, 1):
            j = ms[0]; a, b = g.arcs[j]
            title = 'VP: %s +Pi2(%d-%d)' % (g.volkov(), a+1, b+1)
            names3.append(emit(g, wt, 'v3_%02d' % i, [j], cache, out, title)); i += 1
    write_table(out, 2, names2); write_table(out, 3, names3)
    print('VP graphs:', names2, names3)

if __name__ == '__main__':
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 3)
