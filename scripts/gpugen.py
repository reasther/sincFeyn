#!/usr/bin/env python3
"""gpugen.py -- CUDA version of a generated kernel, for the GPU back end (driver/gpu.cu).

The QREAL half of a kernel is a complete scalar copy of the integrand (chunk functions bk_/ab_, the
point function pt_, helpers such as vp_/p_/nd_, the Sinc wrapper f_) written against the REAL macro.
This takes that half and compiles it as double device code:
  - the chunk functions become SQ_CHUNK (__device__ __noinline__ by default);
  - every other function becomes a device function with the global SQ_AB as an extra last parameter,
    passed on at every call; inlined if it is called once, a real call otherwise (vp_ calls pt_ 2-4 times);
  - the Gauss-Legendre tables go to __constant__ memory;
  - a __global__ kernel evaluates a batch of lattice nodes, one thread per node (gpu_kernel.h):
        out_f[i] = f(sf) * w,  out_ab[i] = sum|terms| * w,   w = prod(sf h) (as lattice_node).
The double-double fallback stays on the host (scripts/ddvgen.py, SIMD): a double-double device version
of the four-loop kernels does not compile (ptxas runs out of memory at 94 GB, also at -O0).

    python3 scripts/gpugen.py kernels-ext/g4/g4_101.c build/gpu/g4_101.cu
"""
import re, sys

def qreal_half(src):
    """(name, D, body of the QREAL half, GL table lines)"""
    txt = open(src).read()
    m = re.search(r'^const graph_t G_(\w+)=\{"([^"]*)","[^"]*",(\d+),(\d+),', txt, re.M)
    name, D = m.group(1), int(m.group(4))
    i = txt.index('#define REAL QREAL')
    j = txt.index('#define FN(x) x##_q', i) + len('#define FN(x) x##_q')
    k = txt.index('#undef REAL', j)
    gl = re.findall(r'^static const double (GLX_\w+\[\d+\]=\{[^}]*\}), (GLW_\w+\[\d+\]=\{[^}]*\});', txt, re.M)
    return name, D, txt[j:k], gl

def close_paren(s, i):
    """index of the ')' matching the '(' at s[i]"""
    d = 0
    for p in range(i, len(s)):
        if s[p] == '(': d += 1
        elif s[p] == ')':
            d -= 1
            if d == 0: return p
    raise ValueError('unbalanced')

def add_sqab(body, qual_once, qual_many):
    """SQ_AB as the last parameter of every function except the chunk functions (bk_/ab_), and as the
    last argument of every call to them; qualifiers by number of call sites.  Returns (body, names)."""
    defs = re.findall(r'^static (?:REAL|void) FN\((\w+)\)\(', body, re.M)
    names = [n for n in defs if not re.match(r'(bk|ab)_', n)]
    for n in names:
        # calls first (the definition is "FN(n)(" too: skip the one preceded by the return type)
        out, pos = [], 0
        for m in re.finditer(r'FN\(%s\)\(' % re.escape(n), body):
            if re.search(r'static (REAL|void) $', body[max(0, m.start() - 12):m.start()]): continue
            c = close_paren(body, m.end() - 1)
            out.append(body[pos:c]); out.append(',SQ_AB'); pos = c
        out.append(body[pos:]); body = ''.join(out)
        ncalls = len(re.findall(r'FN\(%s\)\(' % re.escape(n), body)) - 1
        m = re.search(r'^static (REAL|void) FN\(%s\)\(' % re.escape(n), body, re.M)
        c = close_paren(body, m.end() - 1)
        # the pieces tools/splitform.py cuts a large FORM block into (<node>_cB_K, five loops) are called
        # once each, but inlining them all into one kernel gave g5_3086 a 51 KB stack frame and 119 KB of
        # spill stores; as real calls it is 31 KB and 18 KB (+ ~1-3 KB per piece)
        q = qual_once if ncalls <= 1 and not re.search(r'_c\d+_\d+$', n) else qual_many
        body = body[:m.start()] + 'static %s %s FN(%s)(' % (q, m.group(1), n) + body[m.end():c] + ', const int SQ_AB' + body[c:]
    return body, names

def convert(src):
    name, D, body, gl = qreal_half(src)
    # F (inputs) and T (shared sub-sums) are always distinct arrays
    nchunk = len(re.findall(r'^static void FN\((?:bk|ab)_\w+\)\(', body, re.M))
    body, nc = re.subn(r'^static void FN\(((?:bk|ab)_\w+)\)\(const REAL \*F, REAL \*T\)\{',
                       r'static SQ_CHUNK void FN(\1)(const REAL *__restrict__ F, REAL *__restrict__ T){', body, flags=re.M)
    assert nc == nchunk, (src, nc, nchunk)
    body, names = add_sqab(body, '__device__ __forceinline__', '__device__ __noinline__')
    assert 'f_' + name in names, (src, names)
    assert 'static' not in re.sub(r'static (SQ_CHUNK|__device__)', '', body), src
    out = ['/* generated by scripts/gpugen.py from %s: double device version of the QREAL half */' % src,
           '#include "gpu_kernel.h"']
    for x, w in gl:
        out.append('static __constant__ double %s, %s;' % (x, w))
    out += ['#define REAL double', '#define FN(x) x##_g', body, '#undef REAL', '#undef FN',
            'SQ_GPU_KERNEL(%s, %d)' % (name, D)]
    return name, '\n'.join(out) + '\n'

if __name__ == '__main__':
    name, code = convert(sys.argv[1])
    open(sys.argv[2], 'w').write(code)
