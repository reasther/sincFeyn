#!/usr/bin/env python3
"""ddvgen.py -- SIMD double-double version of a generated kernel: the high-precision fallback for
SQ_DDVW points at once (8 with AVX-512), one per vector lane (driver/ddv.h).

The QREAL half of a kernel (chunk functions, pt_, helpers, f_) is written against the REAL macro and,
except in the Pi4 parts (v3_p4*, w3_*), has no branches on values (only on SQ_AB, and RABS), so it runs
unchanged with REAL = ddv.  SQ_AB becomes a parameter (always 1 here: the fallback needs the |.| sums),
RABS a lane-wise select.  The
wrapper fv_<graph>(m, sf, v, ab) evaluates m <= SQ_DDVW points (sf: m x D) and returns per point
v = (double) f and ab = (double) sum|terms|, as (double) of the scalar dd version.

    python3 tools/ddvgen.py kernels-ext/g4/g4_181.c build/ddv/g4_181.cc
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gpugen import qreal_half, add_sqab

def convert(src):
    name, D, body, gl = qreal_half(src)
    hdr = '/* generated by tools/ddvgen.py from %s: SIMD double-double version of the QREAL half */' % src
    # lanes run in lockstep: a kernel that branches on computed values (the Pi4 parts v3_p4*, w3_*)
    # gets no SIMD version (no GV_ symbol; the registry reference is weak) and keeps the scalar fallback
    ifs = set(re.findall(r'\bif\(([^)]*)\)', body)) - {'SQ_AB'}
    if ifs or '?' in re.sub(r'/\*.*?\*/', '', body, flags=re.S):
        return name, hdr + '\n/* not vectorised: branches on values (%s) */\n' % '; '.join(sorted(ifs))[:200]
    body, names = add_sqab(body, '', '')
    assert 'f_' + name in names, (src, names)
    out = [hdr, '#include "ddv.h"', '#include "ddvk.h"', '#define RABS(x) ddv_abs(x)']
    out += ['static const double %s, %s;' % (x, w) for x, w in gl]
    out += ['#define REAL ddv', '#define FN(x) x##_v', body, '#undef REAL', '#undef FN']
    out.append('''static void fv_%(n)s(int m, const double *sf, double *v, double *ab){
    ddv s[%(D)d], a;
    for(int d = 0; d < %(D)d; d++) for(int l = 0; l < SQ_DDVW; l++) s[d].hi[l] = sf[(l < m ? l : 0)*%(D)d + d];
    ddv f = f_%(n)s_v(s, &a, 1);
    for(int l = 0; l < m; l++){ v[l] = f.hi[l] + f.lo[l]; ab[l] = a.hi[l] + a.lo[l]; }
}
extern "C" const sq_ddv_t GV_%(n)s = {"%(n)s", %(D)d, SQ_DDVW, fv_%(n)s};''' % {'n': name, 'D': D})
    return name, '\n'.join(out) + '\n'

if __name__ == '__main__':
    name, code = convert(sys.argv[1])
    open(sys.argv[2], 'w').write(code)
